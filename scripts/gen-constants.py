#!/usr/bin/env python3
"""gen-constants.py FILE CLASS : replace `defineConstants(context, CLASS.class)` (reflection over
@JRubyConstant fields) with a generated explicit method, as TeaVM keeps no field metadata."""
import re, sys
f, cls = sys.argv[1], sys.argv[2]
s = open(f).read()
fields = re.findall(r'@JRubyConstant(?:\((?:value\s*=\s*)?(\{[^}]*\}|"[^"]*")\))?\s*\n\s*(?:public |protected |private )?(?:static final|final static) (int|short|byte|boolean|String) (\w+)', s)
lines = []
for names, tp, name in fields:
    ns = re.findall(r'"([^"]*)"', names) if names else [name]
    if tp in ('int', 'short', 'byte'): val = f'asFixnum(context, {name})'
    elif tp == 'boolean': val = f'asBoolean(context, {name})'
    else: val = f'newString(context, {name})'
    for n in ns:
        lines.append(f'        module.defineConstant(context, "{n}", {val});')
method = ('\n    // TEAVM: generated by scripts/gen-constants.py from the @JRubyConstant fields above; replaces the\n'
          '    // reflective RubyModule.defineConstants(context, Class) (TeaVM keeps no field/annotation metadata)\n'
          f'    private static <T extends RubyModule> void defineJRubyConstants(ThreadContext context, T module) {{\n'
          + '\n'.join(lines) + '\n    }\n')
call = f'defineConstants(context, {cls}.class)'
assert s.count(call) == 1, call
s = s.replace(call, 'tap(m -> defineJRubyConstants(context, (RubyModule) m))')
i = s.rindex('}')
s = s[:i] + method + s[i:]
open(f, 'w').write(s)
print(f, len(lines), 'constants')
