#!/bin/bash
# gen-registry.sh GENDIR OUTDIR : write OUTDIR/org/jruby/gen/PopulatorRegistryImpl.java (a switch over the
# generated $POPULATOR sources in GENDIR, minus the excluded ones) and OUTDIR/META-INF/services entry.
set -eu
gen=$1; out=$2
here=$(cd "$(dirname "$0")/.." && pwd)
mkdir -p $out/org/jruby/gen $out/META-INF/services
# Excluded: Ripper, Digest (no MessageDigest), JRubyObjectInputStream (Java serialization), $CLASSPATH,
# java.time extensions (TeaVM has no java.time).
EXCL='^org\$jruby\$(ext\$ripper\$|ext\$digest\$|ext\$jruby\$JRubyObjectInputStream|RubyClassPathVariable|javasupport\$ext\$JavaTime\$)'
f=$out/org/jruby/gen/PopulatorRegistryImpl.java
{
echo "/* GENERATED by scripts/gen-registry.sh - static registry of pregenerated populators (TeaVM build) */"
echo "package org.jruby.gen;"
echo "public final class PopulatorRegistryImpl implements org.jruby.anno.PopulatorRegistry {"
echo "    @Override public org.jruby.anno.TypePopulator forName(String n) {"
echo "        switch (n) {"
for p in $(ls $gen | sed 's/\.java$//' | grep -Ev "$EXCL" ${EXTRA_EXCL:+| grep -Ev "$EXTRA_EXCL"} | sort); do
  echo "            case \"org.jruby.gen.$p\": return new org.jruby.gen.$p();"
done
echo "            default: return null;"
echo "        }"
echo "    }"
echo "}"
} > $f
echo org.jruby.gen.PopulatorRegistryImpl > $out/META-INF/services/org.jruby.anno.PopulatorRegistry
echo "registry: $(grep -c 'case "' $f) populators"

# Java classes that Ruby code can load by name (java.util.ArrayList, java_import ...): the first word of every
# line of java-classes.txt -> org.jruby.gen.JavaClassRegistryImpl (a switch returning class literals, which also
# makes TeaVM compile the classes in). Their reflection metadata comes from teavm-plugin/JavaClassesPolicy.
f=$out/org/jruby/gen/JavaClassRegistryImpl.java
{
echo "/* GENERATED by scripts/gen-registry.sh from java-classes.txt - Java classes Ruby can load by name (TeaVM build) */"
echo "package org.jruby.gen;"
echo "public final class JavaClassRegistryImpl implements org.jruby.javasupport.JavaClassRegistry {"
echo "    @Override public Class<?> forName(String n) {"
echo "        switch (n) {"
for c in $(sed 's/#.*//' "$here/java-classes.txt" | awk 'NF { print $1 }'); do
  echo "            case \"$c\": return ${c//\$/.}.class;"
done
echo "            default: return null;"
echo "        }"
echo "    }"
echo "}"
} > $f
echo org.jruby.gen.JavaClassRegistryImpl > $out/META-INF/services/org.jruby.javasupport.JavaClassRegistry
echo "java classes: $(grep -c 'case "' $f)"
